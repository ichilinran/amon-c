import {readFile,writeFile} from 'node:fs/promises';
import {gunzipSync,gzipSync} from 'node:zlib';
import {createHash} from 'node:crypto';
import path from 'node:path';
import createModule from '../wasm/out/shi-clang.mjs';
import {createWasmAnalyzer} from '../src/runtime/wasm-runtime.js';
import cases from '../tests/cases.mjs';
const wasmBinary=await readFile(new URL('../wasm/out/shi-clang.wasm',import.meta.url));
const sdkFiles=JSON.parse(gunzipSync(await readFile(new URL('../wasm/out/sdk.json.gz',import.meta.url))));
const result=await createWasmAnalyzer({createModule:o=>createModule({...o,wasmBinary}),sdkFiles})({source:cases.allHeaders});
if(!result.native.valid)throw new Error('SDK dependency acquisition failed');
const used=new Set(result.native.fileInstances.filter(i=>i.physicalFile).map(i=>path.posix.normalize(i.file)));
const core=sdkFiles.filter(f=>used.has(f.path));
const gzip=gzipSync(Buffer.from(JSON.stringify(core)),{mtime:0});
const binaryGzip=gzipSync(wasmBinary,{level:9,mtime:0});
const index={fullSdkSha256:createHash('sha256').update(await readFile(new URL('../wasm/out/sdk.json.gz',import.meta.url))).digest('hex'),paths:sdkFiles.map(f=>f.path)};
await writeFile(new URL('../wasm/out/sdk-core.json.gz',import.meta.url),gzip);
await writeFile(new URL('../wasm/out/shi-clang.wasm.gz',import.meta.url),binaryGzip);
await writeFile(new URL('../wasm/out/sdk-index.json',import.meta.url),JSON.stringify(index)+'\n');
await writeFile(new URL('../wasm/core-sdk-report.json',import.meta.url),JSON.stringify({fullHeaders:sdkFiles.length,coreHeaders:core.length,coreGzipBytes:gzip.length,wasmGzipBytes:binaryGzip.length,wasmRawBytes:wasmBinary.length,fullFallbackPreserved:true},null,2)+'\n');
console.log({fullHeaders:sdkFiles.length,coreHeaders:core.length,coreBytes:gzip.length,wasmGzip:binaryGzip.length});
